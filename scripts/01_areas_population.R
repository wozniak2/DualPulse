## ── 01 · Osiedle boundaries (OpenStreetMap) ────────────────────────────────────────────────────────────────
section("01", "Osiedle boundaries (OpenStreetMap)", {
  ## Fetch Poznań's 42 osiedle (jednostki pomocnicze / rady osiedli) boundary
  ## polygons from OpenStreetMap -- the spatial unit the real 2021 GPR poverty
  ## rate (data/diagnoza2021_osiedla_ground_truth.csv) is reported at, and
  ## that this project's whole current approach joins population and
  ## deprivation data onto. No official machine-readable boundary file for
  ## these 42 units was located (the source documents only ship them as
  ## raster map images); OSM carries them, verified directly rather than
  ## assumed.
  ##
  ## Real gotcha found while fetching (worth remembering if this is ever
  ## re-run): Poznań's `boundary=administrative` osiedla sit at `admin_level=9`
  ## in OSM, NOT 10 -- admin_level=10 in this bbox instead returns a mix of
  ## older historical sub-neighbourhood names (the pieces some of the 42 hyphen-
  ## ated official names are built from, e.g. "Ostrów Tumski"/"Śródka"/"Zawady"
  ## separately) and informal housing-estate polygons ("Osiedle Jagiellońskie"
  ## etc., a different sense of the Polish word "osiedle"), and querying it
  ## returns 0/42 useful exact matches. admin_level=9 matches 40 of 42 directly.
  ## The remaining 2 are a real renaming, not a data gap: the Diagnoza (2016)
  ## uses "Jana III Sobieskiego i Marysieńki" and "Św. Łazarz", which OSM
  ## records as `old_name` on "Piątkowo Północ" and current `name` "Łazarz"
  ## respectively (confirmed via a direct Overpass name-regex query, not
  ## guessed) -- both mapped explicitly below rather than left as a silent gap.
  ## admin_level=9 also over-returns a handful of ring-municipality units that
  ## leak into the bounding box (Lasek, Robakowo, Stary Luboń, Żabikowo,
  ## belonging to Kórnik/Luboń) -- dropped by the exact-42-name filter.
  ##
  ## This project's data/diagnoza2021_osiedla_ground_truth.csv (the 42-row
  ## table of real osiedle names + the 2021 GPR poverty rate, hand-transcribed
  ## from the official monitoring report -- see the project README) MUST
  ## already exist before this script runs; it isn't generated by any script
  ## here. (Two earlier ground-truth vintages, 2016 and 2019, also exist in
  ## data/ as real historical reference -- see README -- but nothing in the
  ## current pipeline depends on them; 2021 is the most recent real data and
  ## the one this project's current approach uses throughout.)

  suppressPackageStartupMessages({
    library(sf); library(dplyr); library(osmdata)
  })

  out_dir <- ROOT
  out_gpkg <- file.path(out_dir, "output", "osiedla_42_boundaries.gpkg")
  gt_csv   <- file.path(out_dir, "data", "diagnoza2021_osiedla_ground_truth.csv")

  ## Overpass's main endpoint (overpass-api.de) has been noticeably flaky in
  ## the past -- cache the raw fetch immediately so a re-run of this script
  ## never needs to hit it again. A pre-fetched cache ships with this project
  ## (output/_admin9_raw.gpkg, output/_strzeszyn.gpkg) so a fresh checkout
  ## normally skips the network entirely; delete them to force a re-fetch.
  raw_cache <- file.path(out_dir, "output", "_admin9_raw.gpkg")
  bb <- c(16.75, 52.30, 17.10, 52.50)  # xmin,ymin,xmax,ymax
  if (file.exists(raw_cache)) {
    cat("Using cached admin_level=9 fetch (", raw_cache, ") -- delete it to force a re-fetch.\n")
    polys <- st_read(raw_cache, quiet = TRUE)
  } else {
    q <- opq(bbox = bb, timeout = 180) %>%
      add_osm_feature(key = "boundary", value = "administrative") %>%
      add_osm_feature(key = "admin_level", value = "9")
    cat("Fetching admin_level=9 boundaries via osmdata (Overpass)...\n")
    osm <- osmdata_sf(q)
    polys <- osm$osm_multipolygons
    if (is.null(polys) || nrow(polys) == 0) polys <- osm$osm_polygons
    polys <- polys %>% select(osm_id, name) %>% st_make_valid()
    st_write(polys, raw_cache, delete_dsn = TRUE, quiet = TRUE)
  }
  cat("Have", nrow(polys), "admin_level=9 polygons in the bbox\n")

  ## the 2 confirmed renames (see header) -- rename OSM's current name back to
  ## the Diagnoza's 2016 name so the join in step below is a plain exact match
  polys <- polys %>%
    mutate(name = case_when(
      name == "Łazarz"          ~ "Św. Łazarz",
      name == "Piątkowo Północ" ~ "Jana III Sobieskiego i Marysieńki",
      TRUE ~ name
    ))

  gt <- read.csv(gt_csv, fileEncoding = "UTF-8")
  matched <- polys %>% filter(name %in% gt$osiedle) %>% distinct(name, .keep_all = TRUE)

  ## Strzeszyn (relation 3244393) is real and tagged boundary=administrative,
  ## admin_level=9 -- but osmdata_sf() returns 0 polygons for it (486 points /
  ## 15 linestrings, no assembled ring), apparently because this relation
  ## carries only `type=boundary`, not the `type=multipolygon` osmdata's
  ## polygon-assembly logic expects, unlike the other 41 (which have both).
  ## Confirmed by direct inspection, not assumed. Worked around by fetching
  ## this one relation's member ways directly (`opq_osm_id`) and polygonising
  ## them by hand (st_line_merge + st_polygonize) -- reproduced area (11.99
  ## km2) matches the Diagnoza's own reported 12.00 km2, confirming the fix is
  ## correct, not a different/wrong polygon.
  strz_cache <- file.path(out_dir, "output", "_strzeszyn.gpkg")
  if (!"Strzeszyn" %in% matched$name) {
    cat("Strzeszyn missing from the bulk fetch (known osmdata limitation, see comment above) -- patching...\n")
    if (!file.exists(strz_cache)) {
      ## Overpass's main endpoint is flaky; the lz4 mirror worked when this was first fetched.
      strz_q <- opq_osm_id(type = "relation", id = 3244393, overpass_url = "https://lz4.overpass-api.de/api/interpreter") %>% opq_string()
      strz_lines <- osmdata_sf(strz_q)$osm_lines
      strz_poly <- st_union(strz_lines) %>% st_line_merge() %>% st_polygonize() %>%
        st_collection_extract("POLYGON") %>% st_union() %>% st_make_valid()
      st_write(st_sf(name = "Strzeszyn", geometry = st_sfc(strz_poly, crs = 4326)), strz_cache, delete_dsn = TRUE, quiet = TRUE)
    }
    strz_sf <- st_read(strz_cache, quiet = TRUE)
    geom_col <- attr(matched, "sf_column")  # a GPKG round-trip can rename the geometry column (e.g. to "geom") --
                                             # realign to whatever `matched`'s ACTUAL active column is (don't
                                             # hardcode a name) before bind_rows, or the two geometry columns
                                             # silently fail to combine and this row ends up with empty geometry.
    st_geometry(strz_sf) <- geom_col
    strz_sf <- strz_sf %>% mutate(osm_id = "3244393") %>% select(osm_id, name, all_of(geom_col))
    matched <- bind_rows(matched, strz_sf)
  }

  cat("Matched to the 42 official osiedla:", nrow(matched), "of 42\n")
  missing <- setdiff(gt$osiedle, matched$name)
  if (length(missing) > 0) stop("Still missing: ", paste(missing, collapse = ", "))

  ## sanity check: compare OSM-derived area against the 2016 Diagnoza's own
  ## reported area (Table 1) -- large mismatches would indicate a wrong-
  ## boundary match, not just an acceptable digitisation difference. Area is a
  ## static geographic fact, not a year-specific deprivation statistic, so
  ## reusing the 2016 CSV here (only for this column) is fine even though the
  ## rest of this project's pipeline runs on 2021 -- osiedle boundaries don't
  ## change year to year, and only the 2016 source documented area explicitly.
  gt_area <- read.csv(file.path(out_dir, "data", "diagnoza2016_osiedla_ground_truth.csv"), fileEncoding = "UTF-8") %>%
    select(osiedle, area_km2)
  matched_2180 <- st_transform(matched, 2180)
  matched_2180$area_km2_osm <- as.numeric(st_area(matched_2180)) / 1e6
  check <- matched_2180 %>% st_drop_geometry() %>%
    left_join(gt_area, by = c("name" = "osiedle")) %>%
    mutate(area_ratio = area_km2_osm / area_km2)
  cat("\nArea sanity check (OSM area / 2016-reported area, should mostly be ~0.9-1.1):\n")
  print(check %>% select(name, area_km2, area_km2_osm, area_ratio) %>% arrange(area_ratio))

  st_write(matched, out_gpkg, layer = "osiedla_42", delete_dsn = TRUE, quiet = TRUE)
  cat("\nSaved 42 osiedle boundaries to", out_gpkg, "(layer osiedla_42)\n")
})

## ── 02 · 200 m analysis grid ───────────────────────────────────────────────────────────────────────────────
section("02", "200 m analysis grid", {
  ## Builds the 200m x 200m analysis grid over Poznań city -- geometry + cell_id
  ## only. This project's earlier Sentinel-spectral-index and apartment-price
  ## RF modelling approach (which also computed price/green/POI covariates on
  ## this same grid) has been retired -- see README's "Why the earlier
  ## Sentinel/price approach was retired" section. The current approach needs
  ## only the grid's geometry: real address-geocoded population (04, 05) and
  ## the real 2021 osiedle poverty rate (data/diagnoza2021_osiedla_ground_truth.csv)
  ## are joined onto it directly, with no fine-grid covariates of their own.
  ##
  ## Run 01_fetch_osiedla_boundaries.R first (this script only needs poz.gpkg
  ## for the grid extent, not the osiedla boundaries themselves).
  ##
  ## EXTERNAL DEPENDENCY (read-only, not duplicated into this project): a
  ## Poznań-city boundary polygon from the sibling MobilityPatterns project.

  suppressPackageStartupMessages({library(sf); library(dplyr)})

  out_dir <- ROOT
  mp_dir  <- CITY_DIR  # poz.gpkg (city boundary)
  CELL_M  <- 200

  poz <- st_read(file.path(mp_dir, "poz.gpkg"), quiet = TRUE) %>% st_transform(2180) %>% st_union() %>% st_make_valid()
  grid <- st_make_grid(poz, cellsize = CELL_M, what = "polygons") %>% st_sf(cell_id = seq_along(.), geometry = .)
  grid <- grid[st_intersects(grid, poz, sparse = FALSE)[, 1], ]  # keep cells touching the city
  cat("Grid:", nrow(grid), "cells of", CELL_M, "m over Poznań city\n")

  out_gpkg <- file.path(out_dir, "output", sprintf("income_map_grid_%dm.gpkg", CELL_M))
  st_write(grid, out_gpkg, layer = "grid", delete_dsn = TRUE, quiet = TRUE)
  cat("Saved grid to", out_gpkg, "\n")
})

## ── 03 · GEOPOZ address points ─────────────────────────────────────────────────────────────────────────────
section("03", "GEOPOZ address points", {
  ## Bulk-fetches ALL real address points for Poznań from GEOPOZ's own address
  ## registry (`iip/system_adresowy`, layer 0 "Punkty adresowe") -- needed as a
  ## geocoding source for the user-supplied `data/pop_geocoded.csv` (real
  ## registered-population counts by street + house number, Wielkopolskie-
  ## wide). That file has ZERO usable coordinates for the 43,004 Poznań-city
  ## rows specifically (confirmed directly: g_dlug/g_szer blank for every
  ## POWIAT=="POZNAŃ" row, vs. 98.3% populated for the surrounding POZNAŃSKI
  ## ring rows -- a real, structural gap in exactly the area this project
  ## needs).
  ##
  ## GUGiK's UUG geocoder (already proven for RealEstatePrices' ring
  ## addresses, 90.7% success there) was tried first per the user's own
  ## suggestion, and found to genuinely fail for Poznań-city addresses right
  ## now -- verified directly with several unambiguous central addresses
  ## (Stary Rynek 1, Święty Marcin 1, Głogowska 14, Adama Biedrzyckiego 1: all
  ## return "found objects">0 but "returned objects":0/"results":null), while
  ## a Warszawa control query worked fine. The historical geocode_cache.csv
  ## from RealEstatePrices only ever geocoded ring addresses (zero Poznań-city
  ## queries in it), so its high success rate never actually covered this
  ## case. Not pursued further -- switched to this exact-match registry
  ## lookup instead, which has no fuzzy-accuracy-threshold failure mode.
  ##
  ## This layer: 59,933 real address points, each with street name + type
  ## (NAZWY_UL_NAZWA/TYPY_UL_TYP), house number (NR), and -- a real bonus,
  ## confirmed directly -- JEDN_POM (osiedle), using the EXACT SAME 42 osiedle
  ## names already used throughout this project's ground-truth CSVs (e.g.
  ## "Św. Łazarz", "Jana III Sobieskiego i Marysieńki") -- so this fetch also
  ## gives free, authoritative osiedle assignment for every address point, no
  ## spatial join needed later.
  ##
  ## Real API constraint, confirmed not assumed: `supportsPagination:false`
  ## and maxRecordCount=1000 -- a plain `where=1=1` query silently truncates
  ## at 1000 with `exceededTransferLimit:true`. Chunking by JEDN_POM (42
  ## osiedla) is a natural first split, but several large osiedla (Piątkowo,
  ## Rataje -- 34,000+ population each) plausibly exceed 1000 points on their
  ## own, so each chunk is checked for truncation and recursively split by
  ## street-name alphabet range until every chunk comes back complete.
  ##
  ## Sequential requests only -- `curl_fetch_multi` was already found to fail
  ## ~98% of the time against this exact host (wms1.geopoz.poznan.pl) in
  ## `13_geopoz_sentinel_extract.R`; no reason to expect this endpoint differs.

  suppressPackageStartupMessages({library(sf); library(dplyr); library(curl); library(jsonlite)})

  out_dir <- ROOT
  BASE <- "https://wms1.geopoz.poznan.pl:6443/arcgis/rest/services/iip/system_adresowy/MapServer/0/query"

  esc <- function(x) URLencode(x, reserved = TRUE)

  fetch_query <- function(where) {
    url <- sprintf("%s?where=%s&outFields=NAZWY_UL_NAZWA,TYPY_UL_TYP,NR,JEDN_POM,MIEJSC_NAZWA&outSR=2177&f=json", BASE, esc(where))
    r <- tryCatch(curl_fetch_memory(url), error = function(e) NULL)
    if (is.null(r) || r$status_code != 200) return(NULL)
    tryCatch(fromJSON(rawToChar(r$content), simplifyVector = FALSE), error = function(e) NULL)
  }

  ## recursively split a where-clause on street-name alphabet ranges until no
  ## chunk is truncated; returns a list of feature-lists
  fetch_all <- function(where, letters_range = c("A", "{")) {
    parsed <- fetch_query(where)
    if (is.null(parsed) || !is.null(parsed$error)) {
      cat("  ! query failed:", where, "\n"); return(list())
    }
    feats <- parsed$features
    truncated <- isTRUE(parsed$exceededTransferLimit)
    if (!truncated || length(letters_range) < 2 || diff(match(letters_range, c(LETTERS, "{"))) < 1) {
      return(feats)
    }
    mid <- LETTERS[ceiling(mean(match(letters_range, c(LETTERS, "{"))))]
    where_lo <- sprintf("(%s) AND UPPER(NAZWY_UL_NAZWA) < '%s'", where, mid)
    where_hi <- sprintf("(%s) AND UPPER(NAZWY_UL_NAZWA) >= '%s'", where, mid)
    c(fetch_all(where_lo, c(letters_range[1], mid)), fetch_all(where_hi, c(mid, letters_range[2])))
  }

  osiedla_names <- c(
    "Antoninek-Zieliniec-Kobylepole","Chartowo","Fabianowo-Kotowo","Grunwald Południe",
    "Grunwald Północ","Górczyn","Głuszyna","Główna","Jana III Sobieskiego i Marysieńki",
    "Jeżyce","Junikowo","Kiekrz","Krzesiny-Pokrzywno-Garaszewo","Krzyżowniki-Smochowice",
    "Kwiatowe","Morasko-Radojewo","Naramowice","Nowe Winogrady Południe","Nowe Winogrady Północ",
    "Nowe Winogrady Wschód","Ogrody","Ostrów Tumski-Śródka-Zawady-Komandoria","Piątkowo",
    "Podolany","Rataje","Sołacz","Stare Miasto","Stare Winogrady","Starołęka-Minikowo-Marlewo",
    "Stary Grunwald","Strzeszyn","Szczepankowo-Spławie-Krzesinki","Umultowo",
    "Warszawskie-Pomet-Maltańskie","Wilda","Winiary","Wola","Zielony Dębiec","Ławica",
    "Św. Łazarz","Świerczewo","Żegrze"
  )
  stopifnot(length(osiedla_names) == 42)

  cache_file <- file.path(out_dir, "output", "geopoz_address_points_raw.rds")
  if (file.exists(cache_file)) {
    all_feats <- readRDS(cache_file)
    cat("Loaded cached fetch:", length(all_feats), "features\n")
  } else {
    all_feats <- list()
    for (nm in osiedla_names) {
      where <- sprintf("JEDN_POM = '%s'", gsub("'", "''", nm))
      feats <- fetch_all(where)
      cat(sprintf("  %-42s %d points\n", nm, length(feats)))
      all_feats <- c(all_feats, feats)
    }
    ## also grab anything NOT matching a known osiedle name (the placeholder
    ## "Jednostka pomocnicza" rows, or truly unassigned points), so the fetch
    ## total can be honestly compared against the service's own reported 59,933
    where_other <- paste0("JEDN_POM NOT IN (", paste0("'", gsub("'", "''", osiedla_names), "'", collapse=","), ")")
    feats_other <- fetch_all(where_other)
    cat(sprintf("  %-42s %d points\n", "(other/unassigned)", length(feats_other)))
    all_feats <- c(all_feats, feats_other)
    saveRDS(all_feats, cache_file)
  }
  cat("\nTotal address points fetched:", length(all_feats), "(service reports 59,933 total city-wide)\n")

  ## flatten to a data.frame + sf points
  attrs <- lapply(all_feats, function(f) as.data.frame(f$attributes, stringsAsFactors = FALSE))
  attrs <- bind_rows(attrs)
  coords <- t(sapply(all_feats, function(f) c(f$geometry$x, f$geometry$y)))
  pts <- st_as_sf(cbind(attrs, x = coords[,1], y = coords[,2]), coords = c("x","y"), crs = 2177)

  cat("Distinct JEDN_POM values in result:", length(unique(pts$JEDN_POM)), "\n")
  cat("Rows with missing/placeholder JEDN_POM:", sum(pts$JEDN_POM == "Jednostka pomocnicza" | is.na(pts$JEDN_POM)), "\n")
  cat("Duplicate (street,number) pairs:", sum(duplicated(paste(pts$NAZWY_UL_NAZWA, pts$NR))), "\n")

  st_write(pts, file.path(out_dir, "output", "geopoz_address_points.gpkg"), delete_dsn = TRUE, quiet = TRUE)
  cat("Saved output/geopoz_address_points.gpkg\n")
})

## ── 04 · Registered population geocoded to address points ──────────────────────────────────────────────────
section("04", "Registered population geocoded to address points", {
  ## Geocodes the user-supplied `data/pop_geocoded.csv` (real registered-
  ## population counts by street + house number, Wielkopolskie-wide -- see
  ## `18_geopoz_address_points.R`'s header for why UUG wasn't usable and why
  ## GEOPOZ's own address registry is the source here instead) for the 43,004
  ## Poznań-city rows, by an exact street-name + house-number join against
  ## `18`'s output (59,933 real GEOPOZ address points, which also carries
  ## JEDN_POM = osiedle, using this project's exact naming convention already).
  ##
  ## Run 03_geopoz_address_points.R first.

  suppressPackageStartupMessages({library(sf); library(dplyr); library(stringr); library(readr)})

  out_dir <- ROOT

  pop <- read_csv(file.path(out_dir, "data", "pop_geocoded.csv"), show_col_types = FALSE, locale = locale(encoding = "UTF-8"))
  pop_city <- pop %>% filter(POWIAT == "POZNAŃ")
  cat("Poznań-city population rows:", nrow(pop_city), "\n")

  addr <- st_read(file.path(out_dir, "output", "geopoz_address_points.gpkg"), quiet = TRUE)
  cat("GEOPOZ address points:", nrow(addr), "\n")

  ## normalize both sides the same way: uppercase, trim, collapse whitespace.
  ## Street names on both sides omit the type prefix (ul./al./pl.) already, so
  ## no prefix-stripping needed. House numbers compared as-is (uppercase) --
  ## GEOPOZ's NR field uses the same "123A"/"1/3I" conventions as the
  ## population file's NR_DOMU, confirmed by inspecting both samples directly.
  norm <- function(x) str_squish(str_to_upper(x))

  pop_city <- pop_city %>% mutate(join_ulica = norm(ULICA), join_nr = norm(NR_DOMU))
  addr_df <- addr %>% st_drop_geometry() %>%
    mutate(join_ulica = norm(NAZWY_UL_NAZWA), join_nr = norm(NR)) %>%
    select(join_ulica, join_nr, JEDN_POM)
  addr_geom <- st_coordinates(addr)
  addr_df$x <- addr_geom[,1]; addr_df$y <- addr_geom[,2]

  ## de-dupe the address side on the join key before joining (3 real
  ## duplicates found in `18`'s output, confirmed negligible) -- keep first
  addr_df <- addr_df %>% distinct(join_ulica, join_nr, .keep_all = TRUE)

  matched <- pop_city %>% left_join(addr_df, by = c("join_ulica","join_nr"))
  n_matched <- sum(!is.na(matched$x))
  cat(sprintf("\nMatched: %d / %d (%.1f%%)\n", n_matched, nrow(matched), 100*n_matched/nrow(matched)))

  ## ── Inspect failures for any quick, real, systematic fix ────────────────
  unmatched <- matched %>% filter(is.na(x))
  cat("\nSample unmatched (street | house_no):\n")
  print(unmatched %>% distinct(ULICA, NR_DOMU) %>% slice_head(n = 25), n = 25)

  cat("\nMost common unmatched street names (by row count):\n")
  print(unmatched %>% count(ULICA, sort = TRUE) %>% slice_head(n = 15))

  ## Save whatever the plain exact join achieves -- honest, not padded.
  matched_sf <- matched %>% filter(!is.na(x)) %>% st_as_sf(coords = c("x","y"), crs = st_crs(addr))
  st_write(matched_sf, file.path(out_dir, "output", "pop_poznan_geocoded.gpkg"), delete_dsn = TRUE, quiet = TRUE)

  pop_check <- sum(matched_sf$LICZBA_ZAMELDOWANYCH_OGÓŁEM)
  pop_total_city <- sum(pop_city$LICZBA_ZAMELDOWANYCH_OGÓŁEM)
  cat(sprintf("\nPopulation captured by matched rows: %d of %d city total (%.1f%%)\n",
              pop_check, pop_total_city, 100*pop_check/pop_total_city))
  cat("Saved output/pop_poznan_geocoded.gpkg\n")
})

## ── 05 · Population on the 200 m grid ──────────────────────────────────────────────────────────────────────
section("05", "Population on the 200 m grid", {
  ## Aggregates the real, address-geocoded population (04) onto the project's
  ## existing 200m grid -- a real population-density layer, not a global
  ## gridded proxy. Sum, not mean: LICZBA_ZAMELDOWANYCH_OGÓŁEM is a real count
  ## of registered residents at that address, so summing every address point
  ## that falls in a cell gives that cell's real registered population.
  ##
  ## Run 02 (grid) and 04 (geocoded population) first.

  suppressPackageStartupMessages({library(sf); library(dplyr)})

  out_dir <- ROOT

  grid <- st_read(file.path(out_dir, "output", "income_map_grid_200m.gpkg"), quiet = TRUE)
  pop <- st_read(file.path(out_dir, "output", "pop_poznan_geocoded.gpkg"), quiet = TRUE) %>%
    st_transform(st_crs(grid))

  ## point-in-polygon join (grid cells are non-overlapping, so this is exact,
  ## no double-counting) -- st_join keeps every point, then aggregate by cell_id
  joined <- st_join(pop, grid["cell_id"], join = st_within)
  cat("Population points outside any grid cell (should be ~0, city boundary edge):",
      sum(is.na(joined$cell_id)), "of", nrow(joined), "\n")

  cell_pop <- joined %>% st_drop_geometry() %>% filter(!is.na(cell_id)) %>%
    group_by(cell_id) %>%
    summarise(population = sum(LICZBA_ZAMELDOWANYCH_OGÓŁEM, na.rm = TRUE),
              n_addresses = n(), .groups = "drop")

  grid_pop <- grid %>% left_join(cell_pop, by = "cell_id") %>%
    mutate(population = ifelse(is.na(population), 0, population),
           n_addresses = ifelse(is.na(n_addresses), 0, n_addresses))

  cat("\nCells with zero registered population:", sum(grid_pop$population == 0), "of", nrow(grid_pop),
      sprintf("(%.1f%%)\n", 100*mean(grid_pop$population == 0)))
  cat("Total gridded population:", sum(grid_pop$population),
      " (vs. 449,706 real geocoded total -- should match exactly, pure aggregation)\n")
  cat("Max cell population:", max(grid_pop$population), " median (nonzero cells):",
      median(grid_pop$population[grid_pop$population > 0]), "\n")

  st_write(grid_pop, file.path(out_dir, "output", "population_grid_200m.gpkg"), delete_dsn = TRUE, quiet = TRUE)
  cat("\nSaved output/population_grid_200m.gpkg\n")
})

## ── 06 · Zoning of the 2023 structure plan ─────────────────────────────────────────────────────────────────
section("06", "Zoning of the 2023 structure plan", {
  ## Bulk-downloads GEOPOZ's official 2023 land-use designation layer
  ## (`SIPII/Studium_2023`, layer 6 "Kierunkowe przeznaczenie terenu" -- the
  ## city's Studium uwarunkowań i kierunków zagospodarowania przestrzennego,
  ## its structure/master plan) and classifies each of the city's 1,739
  ## land-use zones as residential-relevant or not, then computes each 200m
  ## grid cell's residential-zone area fraction.
  ##
  ## Real category codes, confirmed directly from the layer's own renderer
  ## (not guessed/assumed):
  ##   MN, MW, MN/MW, MN/U, MW/U, MW/MN  -> residential (single/multi-family,
  ##                                        mixed with services)
  ##   ZN, ZO, ZP, ZD, ZC, UF            -> green/excluded (parks, forests,
  ##                                        cemeteries, allotments)
  ##   U, U/P, US                        -> pure services/commercial/sport
  ##   L, KD-*, kk, ktp                  -> transport (airport, roads, rail)
  ##   K, W, O                           -> waste/infrastructure
  ## Non-residential categories are EXCLUDED from the population-weighting
  ## denominator in `22` -- a real address point can still fall inside one of
  ## these zones (e.g. a caretaker's residence in an industrial zone), so this
  ## is used as a down-weighting mask on the dasymetric surface, not to drop
  ## real population data.
  ##
  ## Run 02 (grid) first.

  suppressPackageStartupMessages({library(sf); library(dplyr); library(curl); library(jsonlite)})

  out_dir <- ROOT
  BASE <- "https://wms1.geopoz.poznan.pl:6443/arcgis/rest/services/SIPII/Studium_2023/MapServer/6/query"

  ## bulk fetch, chunked by FID range -- no resultOffset pagination support
  ## (confirmed: supportsPagination:false, same as the address-point layer),
  ## and a plain query DOES hit the 1000-record transfer limit despite 1,739
  ## being under most services' default caps (this one caps at exactly 1000
  ## records, confirmed directly). Recursive FID-range splitting, same
  ## approach as 03's street-letter splitting, generalized to a numeric field.
  fetch_chunk <- function(where) {
    url <- sprintf("%s?where=%s&outFields=*&outSR=2177&f=json", BASE, URLencode(where, reserved = TRUE))
    r <- curl_fetch_memory(url)
    if (r$status_code != 200) return(NULL)
    fromJSON(rawToChar(r$content), simplifyVector = FALSE)
  }
  fetch_all_zones <- function(where, lo, hi) {
    parsed <- fetch_chunk(where)
    if (is.null(parsed) || !is.null(parsed$error)) { cat("  ! failed:", where, "\n"); return(list()) }
    if (!isTRUE(parsed$exceededTransferLimit) || hi - lo < 2) return(parsed$features)
    mid <- lo + floor((hi - lo) / 2)
    c(fetch_all_zones(sprintf("(%s) AND FID <= %d", where, mid), lo, mid),
      fetch_all_zones(sprintf("(%s) AND FID > %d", where, mid), mid, hi))
  }
  ## the zoning layer is cached after the first download, so reruns do not depend on the live service
  zones_file <- file.path(out_dir, "output", "studium2023_landuse_zones.gpkg")
  if (file.exists(zones_file)) {
    zones <- st_read(zones_file, quiet = TRUE)
  } else {
  all_features <- fetch_all_zones("1=1", 0, 5000)
  cat("Fetched", length(all_features), "land-use zones (service reports 1,739 total)\n")
  parsed <- list(features = all_features)

  feat_to_sfg <- function(f) {
    rings <- f$geometry$rings
    st_polygon(lapply(rings, function(r) matrix(unlist(r), ncol = 2, byrow = TRUE)))
  }
  geoms <- st_sfc(lapply(parsed$features, function(f) tryCatch(feat_to_sfg(f), error = function(e) st_polygon())), crs = 2177)
  attrs <- bind_rows(lapply(parsed$features, function(f) as.data.frame(f$attributes, stringsAsFactors = FALSE)))
  zones <- st_sf(attrs, geometry = geoms)
  zones <- zones[!st_is_empty(zones), ]
  cat("Valid zone polygons:", nrow(zones), "\n")

  ## classify by the symb_t_o code (the field driving the renderer's
  ## uniqueValueInfos, confirmed in the layer's own JSON definition)
  residential_codes <- c("MN","MW","MN/MW","MW/MN","MN/U","MW/U")
  zones <- zones %>% mutate(
    land_class = case_when(
      symb_t_o %in% residential_codes ~ "residential",
      TRUE ~ "non_residential"
    )
  )
  cat("\nZone area by class:\n")
  print(zones %>% st_drop_geometry() %>% group_by(land_class) %>%
          summarise(n = n(), area_km2 = round(sum(st_area(zones[zones$land_class==land_class[1],]))/1e6, 1)))

  st_write(zones, file.path(out_dir, "output", "studium2023_landuse_zones.gpkg"), delete_dsn = TRUE, quiet = TRUE)
  }

  ## ── Residential-area fraction per 200m grid cell ─────────────────────────
  grid <- st_read(file.path(out_dir, "output", "income_map_grid_200m.gpkg"), quiet = TRUE)
  zones_res <- zones %>% filter(land_class == "residential") %>% st_make_valid() %>% st_transform(st_crs(grid))

  ## exact_extract-style area overlap via direct intersection (zones layer is
  ## small, 1,739 polygons -- a plain st_intersection is fine here, no need
  ## for exactextractr's raster-oriented machinery)
  inter <- suppressWarnings(st_intersection(grid["cell_id"], st_union(zones_res)))
  inter$res_area_m2 <- as.numeric(st_area(inter))  # compute on the sf object directly -- its
                                                    # geometry column isn't literally named "geometry"
  inter_area <- inter %>% st_drop_geometry() %>% select(cell_id, res_area_m2)

  cell_area <- as.numeric(st_area(grid[1,]))  # 200x200 grid, all cells equal area
  grid_mask <- grid %>% left_join(inter_area, by = "cell_id") %>%
    mutate(res_area_m2 = ifelse(is.na(res_area_m2), 0, res_area_m2),
           residential_frac = pmin(res_area_m2 / cell_area, 1))

  cat("\nCell-level residential_frac summary:\n")
  print(summary(grid_mask$residential_frac))
  cat("Cells with >50% residential land:", sum(grid_mask$residential_frac > 0.5), "of", nrow(grid_mask), "\n")

  st_write(grid_mask, file.path(out_dir, "output", "landuse_mask_200m.gpkg"), delete_dsn = TRUE, quiet = TRUE)
  cat("\nSaved output/studium2023_landuse_zones.gpkg and output/landuse_mask_200m.gpkg\n")
})

## ── 07 · Populated cells with the 2021 poverty rate ────────────────────────────────────────────────────────
section("07", "Populated cells with the 2021 poverty rate", {
  ## Combines real address-level population (05) + real 2021 osiedle
  ## deprivation rates (data/diagnoza2021_osiedla_ground_truth.csv) into a
  ## population-weighted deprivation surface -- both ends of the distribution
  ## (deprived AND affluent population), not a binary threshold.
  ##
  ## Deliberately NOT a proxy/model: `deprived_population_est` in each cell is
  ## just (real registered population in that cell) x (that cell's real
  ## osiedle's real 2021 poverty rate / 1000) -- exact dasymetric redistribution
  ## of a real administrative rate using real point population as the weight,
  ## no spectral/green-space covariates involved. Mass-preserving by
  ## construction (summing any osiedle's cells reproduces population x rate
  ## exactly, since the rate is a constant multiplier within that osiedle).
  ##
  ## Land-use role, checked rather than assumed necessary: since population is
  ## real address-point data (not a coarse proxy needing land-use-based
  ## disaggregation), the Studium residential mask (06) isn't needed to
  ## redistribute population -- it's used here only as a validation check
  ## (does real registered population actually fall on residential-classified
  ## land? -- a cross-check on both the geocoding and the land-use
  ## classification) and is carried into the output for any later use (e.g.
  ## excluding non-residential-zone artifacts from a catchment sum), not
  ## applied as a hard filter.
  ##
  ## Run 02, 05, 06, and have data/diagnoza2021_osiedla_ground_truth.csv.

  suppressPackageStartupMessages({library(sf); library(dplyr); library(data.table); library(ggplot2)})

  out_dir <- ROOT
  fig_dir <- file.path(out_dir, "output", "figures")

  pop_grid <- st_read(file.path(out_dir, "output", "population_grid_200m.gpkg"), quiet = TRUE)
  landuse  <- st_read(file.path(out_dir, "output", "landuse_mask_200m.gpkg"), quiet = TRUE) %>%
    st_drop_geometry() %>% select(cell_id, residential_frac)
  osiedla  <- st_read(file.path(out_dir, "output", "osiedla_42_boundaries.gpkg"), quiet = TRUE) %>% st_transform(st_crs(pop_grid))
  gt2021   <- fread(file.path(out_dir, "data", "diagnoza2021_osiedla_ground_truth.csv"), encoding = "UTF-8")

  grid <- pop_grid %>% left_join(landuse, by = "cell_id")

  ## osiedle assignment -- same centroid-then-within pattern used throughout
  ## this project (e.g. 17_nowcast_2025_geopoz_ndwi.R)
  grid_c <- st_centroid(grid)
  grid$osiedle <- osiedla$name[st_nearest_feature(grid_c, osiedla)]
  within_join <- st_join(grid_c, osiedla["name"], join = st_within)
  grid$osiedle[!is.na(within_join$name)] <- within_join$name[!is.na(within_join$name)]

  grid <- grid %>% left_join(gt2021 %>% select(osiedle, indicator_B_poverty_per1000, indicator_B_std_zscore), by = "osiedle")
  cat("Cells with no osiedle/ground-truth match:", sum(is.na(grid$indicator_B_poverty_per1000)), "of", nrow(grid), "\n")

  ## ── Validation check: does real population sit on residential land? ─────
  val <- grid %>% st_drop_geometry() %>% filter(population > 0)
  cat(sprintf("\nValidation -- population-weighted mean residential_frac where people actually live: %.1f%%\n",
              100 * weighted.mean(val$residential_frac, val$population, na.rm = TRUE)))
  cat(sprintf("(vs. city-wide cell-average residential_frac of %.1f%% -- population should concentrate much higher than the city average if both layers are sound)\n",
              100 * mean(grid$residential_frac, na.rm = TRUE)))

  ## ── Dasymetric redistribution -- real population x real osiedle rate ────
  grid$deprived_pop_est <- grid$population * (grid$indicator_B_poverty_per1000 / 1000)
  cat(sprintf("\nTotal estimated deprived population (sum over all cells): %.0f\n", sum(grid$deprived_pop_est, na.rm = TRUE)))
  osiedle_pop <- grid %>% st_drop_geometry() %>% group_by(osiedle) %>% summarise(pop = sum(population, na.rm = TRUE))
  cross_check <- osiedle_pop %>% left_join(gt2021 %>% select(osiedle, indicator_B_poverty_per1000), by = "osiedle") %>%
    summarise(tot = sum(pop * indicator_B_poverty_per1000 / 1000, na.rm = TRUE)) %>% pull(tot)
  cat(sprintf("Cross-check -- osiedle-level (population x rate) summed directly from ground truth: %.0f (should match exactly)\n", cross_check))

  st_write(grid, file.path(out_dir, "output", "population_weighted_deprivation_200m.gpkg"), delete_dsn = TRUE, quiet = TRUE)

  ## ── Map: real population-weighted deprived-resident density ─────────────
  theme_map <- theme_void(base_size = 12) + theme(
    plot.background = element_rect(fill = "#12121a", color = NA), panel.background = element_rect(fill = "#12121a", color = NA),
    plot.title = element_text(color = "white", face = "bold", size = 15, hjust = 0.5),
    plot.subtitle = element_text(color = "grey75", size = 9.5, hjust = 0.5),
    plot.caption = element_text(color = "grey55", size = 7.5),
    legend.position = "bottom", legend.text = element_text(color = "grey80", size = 8), legend.title = element_text(color = "grey80", size = 9)
  )
  pal <- c("#0d2b45", "#241b3d", "#4a2564", "#7b2d8e", "#b93a86", "#e0457b", "#ff7a5c", "#ff9d4d", "#ffc451", "#fff6a0")

  p <- ggplot(grid %>% filter(population > 0)) +
    geom_sf(aes(fill = deprived_pop_est), color = NA) +
    scale_fill_gradientn(colors = pal, name = "Estimated deprived residents / 200m cell", trans = "sqrt") +
    labs(title = "Poznań: real, population-weighted deprived-resident density",
         subtitle = "Real registered address-point population x real 2021 osiedle poverty rate -- no proxy modelling",
         caption = "Population: 42,377 geocoded address points (98.9% of city's registered residents). Deprivation rate: real 2021 GPR monitoring, per osiedle.") +
    theme_map
  ggsave(file.path(fig_dir, "Fig_population_weighted_deprivation_2021.png"), p, width = 10, height = 11, dpi = 200, bg = "#12121a")
  cat("\nSaved output/population_weighted_deprivation_200m.gpkg and figures/Fig_population_weighted_deprivation_2021.png\n")
})

